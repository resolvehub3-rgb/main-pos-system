import { test } from 'node:test'
import assert from 'node:assert/strict'
import { buildTablePdf, buildPrintHtml, textWidth } from './pdf'

/** Decode PDF latin1 bytes back to a JS string for byte-level assertions. */
const latin1 = (bytes: Uint8Array): string => Buffer.from(bytes).toString('latin1')

const report = {
  title: 'My Stock Book',
  metadata: ['Shop: Samtech', 'Range: Jan 2026'],
  columns: [
    { header: 'Product', width: 0.7 },
    { header: 'Closing', width: 0.3, align: 'right' as const },
  ],
  rows: [['Rice 5kg', '40']],
  footer: 'Values at weighted-average cost',
}

test('pdf includes title, metadata, headers, and footer', () => {
  const pdf = latin1(buildTablePdf(report))
  assert.ok(pdf.startsWith('%PDF-1.4'))
  assert.ok(pdf.includes('/Type /Page'))
  assert.ok(pdf.includes('My Stock Book'))
  assert.ok(pdf.includes('Shop: Samtech'))
  assert.ok(pdf.includes('Range: Jan 2026'))
  assert.ok(pdf.includes('Product'))
  assert.ok(pdf.includes('Rice 5kg'))
  assert.ok(pdf.includes('Values at weighted-average cost'))
  assert.ok(pdf.includes('%%EOF'))
})

test('pdf escapes parentheses in cell content', () => {
  const pdf = latin1(
    buildTablePdf({
      title: 'Escapes',
      metadata: [],
      columns: [{ header: 'Name', width: 1 }],
      rows: [['Note (special)']],
    }),
  )
  assert.ok(pdf.includes('Note \\(special\\)'))
})

test('pdf renders GH-currency as latin1 cent sign (byte 0xA2)', () => {
  const pdf = latin1(
    buildTablePdf({
      title: 'Money',
      metadata: [],
      columns: [{ header: 'Value', width: 1 }],
      rows: [['GH\u20B5 3.50']],
    }),
  )
  assert.ok(pdf.includes('GH\u00A2 3.50'))
})

test('print html includes title, meta, table, footer', () => {
  const html = buildPrintHtml({
    title: 'My Report',
    metadata: ['Generated by Samtech Helper'],
    columns: [
      { header: 'Item', width: 0.7 },
      { header: 'Qty', width: 0.3, align: 'right' },
    ],
    rows: [['Soap <bar>', '3']],
    footer: 'End',
  })
  assert.ok(html.includes('<!DOCTYPE html>'))
  assert.ok(html.includes('My Report'))
  assert.ok(html.includes('Generated by Samtech Helper'))
  assert.ok(html.includes('Soap &lt;bar&gt;'))
  assert.ok(html.includes('End'))
  assert.ok(html.includes('@media print'))
  assert.ok(html.includes('display: table-header-group'))
})

test('print html carries no inline script (the popup inherits our CSP)', () => {
  // The report popup inherits `script-src 'self'`, so an inline <script>
  // would be blocked in the desktop app; printReport() triggers print from
  // the opener instead.
  const html = buildPrintHtml({
    title: 'My Report',
    metadata: [],
    columns: [{ header: 'Item', width: 1 }],
    rows: [['Soap']],
  })
  assert.ok(!html.includes('<script'))
  assert.ok(!html.toLowerCase().includes('onload'))
})

test('textWidth estimates proportional widths', () => {
  assert.ok(textWidth('MMMMMM', 10) > textWidth('iiiiii', 10))
  assert.equal(textWidth('', 10), 0)
})
